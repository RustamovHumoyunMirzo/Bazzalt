"""Embed compiler-only image bytes without adding Qt to the compiler."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def Generate(root=ROOT):
    root = Path(root)
    image = (root / "bazzalt/assets/branding/BazzaltLauncher.png").read_bytes()
    output = root / "Compiler/_resources.py"
    output.write_text("# Generated by scripts/embed_compiler_resources.py.\nBRANDING_PNG = " + repr(image) + "\n", encoding="utf-8")
    return output


if __name__ == "__main__":
    Generate()
