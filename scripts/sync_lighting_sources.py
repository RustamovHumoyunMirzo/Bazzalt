"""Synchronize the private Python compiler copy of the embedded GLSL contract."""
from pathlib import Path
import argparse
ROOT=Path(__file__).resolve().parents[1]
def Output():
    source=ROOT/'runtime/resources/shaders'
    return '# Generated by scripts/sync_lighting_sources.py; edit the canonical GLSL files.\nHELPER = '+repr((source/'baked_lighting.glsl').read_text(encoding='utf-8-sig'))+'\nREFLECTIONS = '+repr((source/'baked_reflections.glsl').read_text(encoding='utf-8-sig'))+'\n'
def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args();path=ROOT/'Editor/_lighting_sources.py';text=Output()
    if args.check:
        if not path.is_file() or path.read_text(encoding='utf-8')!=text:raise SystemExit('Run python scripts/sync_lighting_sources.py')
    else:path.write_text(text,encoding='utf-8')
if __name__=='__main__':main()
